use std::future::Future;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use clap::{ArgGroup, Parser, Subcommand};
use wirefox_node::managed::{default_state_dir, LogBuffer, Managed, NodeKey, StateDir};
use wirefox_node::{egress, Node, NodeConfig};

#[cfg(feature = "mimalloc")]
#[global_allocator]
static GLOBAL: mimalloc::MiMalloc = mimalloc::MiMalloc;

#[derive(Parser)]
#[command(
    name = "wirefox-node",
    version,
    about = "WireFox exit-node: reverse-tunnels to the server and sends traffic out of a chosen interface"
)]
struct Cli {
    #[command(subcommand)]
    cmd: Cmd,
}

#[derive(Subcommand)]
enum Cmd {
    /// Connect to the server and start forwarding.
    ///
    /// Standalone, the tunnel is set up from a config file. Given a node key
    /// (in WIREFOX_NODE_KEY or a key file, which keep it off the command line,
    /// or with --key), the node is managed by wirefox-panel, which sends it
    /// the tunnel config.
    #[command(group = ArgGroup::new("managed").args(["key", "key_file"]))]
    Run {
        /// Path to the config file.
        #[arg(short, long, default_value = "node.toml", conflicts_with = "managed")]
        config: PathBuf,
        /// Node key generated by the panel.
        #[arg(long, env = "WIREFOX_NODE_KEY", hide_env_values = true)]
        key: Option<String>,
        /// File holding the node key; keep it readable only by the service.
        #[arg(long, env = "WIREFOX_NODE_KEY_FILE")]
        key_file: Option<PathBuf>,
        /// Where a managed node keeps the config the panel sent it
        /// [default: /var/lib/wirefox-node, or %ProgramData%\wirefox-node on Windows].
        #[arg(long, requires = "managed")]
        state_dir: Option<PathBuf>,
    },
    /// List network interfaces (the names usable in `egress.interface`).
    Interfaces,
}

fn main() -> Result<()> {
    match Cli::parse().cmd {
        Cmd::Interfaces => {
            for i in egress::list_interfaces() {
                let addrs: Vec<String> = i.addrs.iter().map(ToString::to_string).collect();
                let adapter = i.adapter_name.map(|a| format!(" ({a})")).unwrap_or_default();
                let index = i.index.map_or_else(|| "-".into(), |x| x.to_string());
                let state = if i.up { "up" } else { "down" };
                println!("{}{adapter}  index={index}  {state}  {}", i.name, addrs.join(", "));
            }
            Ok(())
        }
        Cmd::Run { config, key, key_file, state_dir } => {
            let key = match (key, key_file) {
                (Some(key), _) => key,
                (None, Some(path)) => std::fs::read_to_string(&path)
                    .with_context(|| format!("reading the node key from {}", path.display()))?
                    .trim()
                    .to_string(),
                (None, None) => return run_standalone(&config),
            };
            run_managed(&key, &state_dir.unwrap_or_else(default_state_dir))
        }
    }
}

fn run_standalone(config: &Path) -> Result<()> {
    wirefox_common::init_tracing("info");
    let node = Node::new(NodeConfig::load(config)?)?;
    tracing::info!(version = wirefox_common::VERSION, "wirefox-node starting");
    run_until_ctrl_c(node.run())
}

fn run_managed(key: &str, state_dir: &Path) -> Result<()> {
    let logs = LogBuffer::default();
    // Every line also goes to the buffer, for the panel to fetch.
    wirefox_common::init_tracing_with("info", logs.layer());
    let node = Managed::new(NodeKey::parse(key)?, StateDir::open(state_dir)?, logs)?;
    tracing::info!(version = wirefox_common::VERSION, state_dir = %state_dir.display(), "wirefox-node starting in managed mode");
    run_until_ctrl_c(node.run())
}

fn run_until_ctrl_c(task: impl Future<Output = ()>) -> Result<()> {
    tokio::runtime::Builder::new_multi_thread().enable_all().build()?.block_on(async {
        tokio::select! {
            () = task => {}
            _ = tokio::signal::ctrl_c() => tracing::info!("shutting down"),
        }
    });
    Ok(())
}
